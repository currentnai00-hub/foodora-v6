"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const html = fs.readFileSync("index.html", "utf8");
const js = fs.readFileSync("homepage-flavorverse.js", "utf8");
const css = fs.readFileSync("homepage-flavorverse.css", "utf8");
assert.match(html, /id="flavorverse"/, "Homepage must include Flavorverse");
assert.match(html, /data-flavor-step="0"/, "Flavor journey must start with step one");
assert.match(html, /data-flavor-step="1" hidden/, "Later steps must start hidden");
assert.match(html, /data-flavor-step="2" hidden/, "Final question must start hidden");
assert.match(html, /homepage-flavorverse\.js/, "Flavorverse controller must load");
assert.match(html, /homepage-flavorverse\.css/, "Flavorverse styling must load");
assert.match(js, /Object\.prototype\.hasOwnProperty\.call\(answers, group\)/, "Only known answer groups may be updated");
assert.match(js, /aria-pressed/, "Choices must expose accessible selected state");
assert.match(js, /availableProducts/, "Suggestions must use available menu products");
assert.match(js, /window\.addToCart\(selectedProductId\)/, "Cart action must use canonical cart logic");
