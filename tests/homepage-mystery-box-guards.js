"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const html = fs.readFileSync("index.html", "utf8");
const css = fs.readFileSync("homepage-mystery-box.css", "utf8");
const js = fs.readFileSync("homepage-mystery-box.js", "utf8");
assert.match(html, /id="fdMysteryBox"/, "Homepage must expose the Mystery Food Box");
assert.match(html, /data-mystery-reveal/, "Mystery reveal must be user initiated");
assert.match(html, /data-mystery-result[^>]*hidden/, "Mystery result must remain hidden until requested");
assert.match(html, /homepage-mystery-box\.js/, "Mystery Box controller must load");
assert.match(js, /getElementById\\("products"\\)/, "Mystery selection must use the real menu");
assert.match(js, /\.add:disabled/, "Unavailable menu items must be excluded");
assert.match(js, /window\.addToCart\(id\)/, "Cart action must use the canonical cart function");
assert.match(js, /currentCard\.querySelector\("\.add"\)\.disabled/, "Stock must be rechecked before adding");
assert.match(js, /Math\.random\(\)/, "Mystery selection must choose a random available menu item");
assert.match(js, /lastProductId/, "Consecutive reveals should avoid repeating the same item when possible");
assert.match(js, /result\.scrollIntoView/, "Revealed result should be brought into view");
assert.match(js, /prefers-reduced-motion: reduce/, "Reveal scrolling must respect reduced motion");
assert.match(css, /prefers-reduced-motion:reduce/, "Animations must respect reduced motion");
assert.match(css, /:focus-visible/, "Controls must expose keyboard focus");
assert.match(js, /typeof window\.addToCart !== "function"/, "Cart action must fail safely when unavailable");
console.log("Homepage Mystery Food Box guards passed.");
